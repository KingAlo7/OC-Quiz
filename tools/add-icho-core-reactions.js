function unique(values) {
  return [...new Set(values.filter(Boolean))];
}

function appendNote(existing, addition) {
  if (!existing) return addition;
  if (existing.includes(addition)) return existing;
  return `${existing} ${addition}`;
}

function mirrorReaction(reaction) {
  return {
    ...reaction,
    id: `icho-core-${reaction.id}`,
    category: ICHO_CATEGORY,
    source_category: reaction.category,
    name: reaction.name,
    notes: appendNote(
      reaction.notes,
      `IChO core mirror from "${reaction.category}": treat this as assumed reaction knowledge for synthesis, mechanism, and structure-elucidation tasks.`
    ),
    tags: unique([...(reaction.tags || []), ...CORE_TAGS, reaction.category]),
  };
}

function special({
  id,
  name,
  difficulty = 'C',
  reaktionstyp,
  transformation,
  general_scheme,
  reagent_label,
  reagent_label_below,
  conditions,
  key_points,
  notes,
  tags,
}) {
  return {
    id: `icho-2026-${id}`,
    category: ICHO_CATEGORY,
    name,
    difficulty,
    reaktionstyp,
    transformation,
    general_scheme: general_scheme || transformation,
    reagent_label,
    reagent_label_below,
    conditions,
    key_points,
    notes,
    tags: unique([...(tags || []), ...SPECIAL_TAGS]),
  };
}

