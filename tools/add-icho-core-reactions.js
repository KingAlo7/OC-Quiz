const refreshed = [
  ...baseEntries,
  ...baseEntries.map(mirrorReaction),
  ...specialEntries,
];

const ids = new Set();
for (const reaction of refreshed) {
  if (ids.has(reaction.id)) throw new Error(`Duplicate reaction id: ${reaction.id}`);
  ids.add(reaction.id);
  for (const key of ['id', 'category', 'name']) {
    if (!reaction[key]) throw new Error(`Missing ${key} on ${reaction.id}`);
  }
}

